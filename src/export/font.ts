export const FONT_FIRST = 0x20;
export const FONT_GLYPHS = GLYPHS.length;

/** Pixel rows of a glyph, 5 bits each (bit 4 = left). */
export function glyphRows(code: number): number[] {
  return GLYPHS[code - FONT_FIRST].split(' ').map((r) => [...r].reduce((v, c) => (v << 1) | (c === '#' ? 1 : 0), 0));
}

/** 2bpp tile data: glyph pixels in colour 3 at x=1..5, y=0..6. */
export function fontTiles(): Uint8Array {
  const out = new Uint8Array(GLYPHS.length * 16);
  for (let g = 0; g < GLYPHS.length; g++) {
    glyphRows(FONT_FIRST + g).forEach((bits, y) => {
      out[g * 16 + y * 2] = bits << 2;
      out[g * 16 + y * 2 + 1] = bits << 2;
    });
  }
  return out;
}

/** Map text to the font: upper case, unknown characters become '?'. */
export function fontText(text: string): number[] {
  return [...text.toUpperCase()].map((c) => {
    const code = c.charCodeAt(0);
    return code >= FONT_FIRST && code < FONT_FIRST + GLYPHS.length ? code : 0x3f;
  });
}
